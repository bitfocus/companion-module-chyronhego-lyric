const BY_CODE = new Map(ERROR_CODES.map((e) => [e.code, e]))

/**
 * The error a code stands for, or undefined if it is not one Lyric documents. Lyric may send a code in lower case, and
 * without its leading zeros.
 */
export function findError(code: string): LyricError | undefined {
	return BY_CODE.get(code.trim().toUpperCase().padStart(8, '0'))
}
