import { InstanceStatus, type LogLevel } from '@companion-module/base'

/** An error code Lyric can return, and how the module reports it */
export interface LyricError {
	/** Eight hex digits, upper case */
	code: string
	label: string
	status: InstanceStatus.UnknownError | InstanceStatus.UnknownWarning
	level: Extract<LogLevel, 'error' | 'warn'>
}

const error = (code: string, label: string): LyricError => ({
	code,
	label,
	status: InstanceStatus.UnknownError,
	level: 'error',
})

const warning = (code: string, label: string): LyricError => ({
	code,
	label,
	status: InstanceStatus.UnknownWarning,
	level: 'warn',
})

